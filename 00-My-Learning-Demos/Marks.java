public class Marks {
    public static void main(String[]args){
        int marks=70;
        if(marks>=90){
            System.out.println("First grade="+marks);
        }
        else if(marks>=80){
            System.out.println("Second grade="+marks);
        }
        else if(marks>=70){
            System.out.println("Third grade="+marks);
        }
        else
            System.out.println("fail="+marks);
    }
}
